def validate_r9_contract() -> None:
    expected = {f"P{index}" for index in range(50)}
    actual = [item.code for item in R9_CONTRACTS]
    if len(actual) != len(set(actual)) or set(actual) != expected:
        raise RuntimeError("R9 contract must contain P0-P49 exactly once")
    if R9_OCCURRENCE_IDS != {"P8", "P22", "P38", "P44", "P49"}:
        raise RuntimeError("R9 occurrence set changed unexpectedly")
    if set(R9_PRODUCT_NAMES) != set(R9_QUALIFIED_IDS):
        raise RuntimeError("every R9 qualified event needs one product mapping")
    if set(R9_TEMPORAL_COMPONENTS) != expected:
        raise RuntimeError("every R9 event needs reviewed temporal components")


validate_r9_contract()
